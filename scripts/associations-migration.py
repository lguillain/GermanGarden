"""Write the vocabulary's word associations as a new Supabase data migration.

Reads data/vocab.sqlite in read-only mode. The migration only inserts rows whose
words exist and that are missing, so it is safe on databases that already have
them and never touches learner progress. Rerun after `pipeline.associations`
changes the associations, then deploy with `supabase db push --linked`.

    python3 scripts/associations-migration.py
"""
import argparse
import json
import sqlite3
from datetime import datetime, timezone
from pathlib import Path


def migration(content: Path) -> str:
    with sqlite3.connect(f'file:{content.resolve()}?mode=ro', uri=True) as conn:
        rows = [dict(word_id=w, related_id=r, rank=k) for w, r, k in conn.execute(
            'SELECT word_id, related_id, rank FROM word_associations ORDER BY word_id, rank')]
    statements = ['-- Generated by scripts/associations-migration.py from the vocabulary pipeline.']
    for start in range(0, len(rows), 500):
        literal = "'" + json.dumps(rows[start:start + 500], ensure_ascii=False).replace("'", "''") + "'::jsonb"
        statements.append(
            'insert into public.word_associations select a.* from jsonb_populate_recordset('
            f'null::public.word_associations, {literal}) a\n'
            'where exists (select 1 from public.words w where w.id = a.word_id)\n'
            'and exists (select 1 from public.words w where w.id = a.related_id)\n'
            'on conflict do nothing;')
    return '\n'.join(statements) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--content', type=Path, default=Path('data/vocab.sqlite'))
    args = parser.parse_args()
    # Follow the repository's YYYYMMDDNNNN migration names.
    folder = Path('supabase/migrations')
    day = datetime.now(timezone.utc).strftime('%Y%m%d')
    taken = [int(p.name[8:12]) for p in folder.glob(f'{day}[0-9][0-9][0-9][0-9]_*.sql')]
    path = folder / f'{day}{max(taken, default=0) + 1:04d}_word_associations_data.sql'
    path.write_text(migration(args.content), encoding='utf-8')
    print(f'Wrote {path}')


if __name__ == '__main__':
    main()
