import { test, expect } from '@playwright/test';

async function onboard(page: import('@playwright/test').Page, name: string) {
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'Who’s learning?' })).toBeVisible();
  await page.getByLabel('New learner').fill(name);
  await page.getByRole('button', { name: 'Create profile' }).click();
  await page.getByLabel('A2 — basic').check();
  await page.getByRole('button', { name: 'Start learning' }).click();
  await expect(page.getByRole('heading', { name: 'Your garden' })).toBeVisible();
}

test('discover, practise, plant, review, and preserve progress', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await onboard(page, 'Browser Learner');
  await page.getByRole('link', { name: 'Find new words', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Find new words' })).toBeVisible();
  const card = page.locator('.word-card');
  await expect(card.getByRole('heading')).toBeVisible();
  const word = await card.getByRole('heading').innerText();
  await page.getByRole('button', { name: 'Show translation' }).click();
  await expect(page.locator('.translation')).toBeVisible();
  await page.getByRole('button', { name: 'Keep word' }).click();
  const bag = page.getByRole('complementary', { name: 'Seed bag', exact: true });
  await expect(bag.getByText('1 / 20')).toBeVisible();
  await expect(bag.getByText(word, { exact: true })).toBeVisible();
  await bag.getByRole('link', { name: 'Practice', exact: true }).click();
  await page.getByRole('link', { name: 'Start flashcards' }).click();
  await expect(page.locator('.word-card')).toContainText(word);
  await page.getByRole('button', { name: 'Show translation' }).click();
  await page.getByRole('button', { name: 'Finish deck' }).click();
  await page.getByRole('link', { name: 'Garden', exact: true }).click();
  await page.getByRole('button', { name: 'Seed bag, 1 of 20 words', exact: true }).click();
  await page.getByRole('complementary', { name: 'Seed bag', exact: true }).getByRole('link', { name: 'Plant', exact: true }).click();
  await page.getByRole('button', { name: 'Show translation' }).click();
  await page.getByRole('button', { name: /^Again In .* Plants seed$/ }).click();
  await expect(page.getByText('Your seeds are planted.')).toBeVisible();
  await page.getByRole('link', { name: 'Garden', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Seed bag, 0 of 20 words', exact: true })).toBeVisible();
  const plot = page.getByRole('button', { name: /^Open .+ planted words$/ }).first();
  await plot.hover();
  await expect(page.locator('.plot-tooltip')).toBeVisible();
  await plot.click();
  await page.getByRole('button', { name: `${word}, Just planted`, exact: true }).click();
  await expect(page.locator('.topic-plant-caption')).toContainText(word);
  await expect(page.locator('.topic-words tbody tr').first()).toContainText(word);
  const topicUrl = page.url();
  await page.getByRole('link', { name: 'Explore topics', exact: true }).first().click();
  const topicPath = new URL(topicUrl).pathname;
  await page.locator(`a.topic-row[href="${topicPath}"]`).click();
  await expect(page).toHaveURL(topicUrl);
  await expect(page.locator('.topic-scene')).toBeVisible();
  await expect(page.locator('.topic-words tbody tr').first()).toContainText(word);
  await page.getByRole('link', { name: 'Garden', exact: true }).click();
  await page.getByRole('link', { name: 'Review words', exact: true }).click();
  await page.getByRole('button', { name: 'Show translation' }).click();
  await page.getByRole('button', { name: /^Good In .* Plant grows$/ }).click();
  await expect(page.getByRole('progressbar', { name: 'Review progress' })).toHaveAttribute('value', '1');
  await expect(page.getByText('1 reviewed', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Review', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Practice', exact: true }).click();
  await page.getByRole('link', { name: 'Start flashcards' }).click();
  await page.getByRole('button', { name: 'Show translation' }).click();
  const progressBefore = await (await page.request.get('/api/garden')).json();
  await expect(page.getByRole('button', { name: 'Learned', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Not yet — repeat', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Finish deck', exact: true }).click();
  const progressAfter = await (await page.request.get('/api/garden')).json();
  expect(progressAfter.plots).toEqual(progressBefore.plots);
  await expect(page.getByRole('heading', { name: 'Deck complete' })).toBeVisible();
  await page.getByRole('link', { name: 'Garden', exact: true }).click();
  await page.screenshot({ path: 'test-results/garden.png', fullPage: true });
  expect(errors).toEqual([]);
});

test('profiles stay separate and unknown routes have a recovery link', async ({ page }) => {
  await onboard(page, 'Second Learner');
  await expect(page.locator('footer')).toHaveCount(0);
  await expect(page.locator('.profile-button .farmer-icon')).toBeVisible();
  await expect(page.getByRole('button', { name: 'Seed bag, 0 of 20 words', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Your progress', exact: true })).toHaveCount(0);
  await page.getByRole('link', { name: 'Explore topics', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Explore more topics' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Explore more topics' })).toBeVisible();
  await page.getByRole('button', { name: /Second Learner/ }).click();
  await expect(page.getByRole('heading', { name: 'Who’s learning?' })).toBeVisible();
  await page.getByRole('button', { name: 'Browser Learner' }).click();
  await expect(page.getByRole('heading', { name: 'Your garden' })).toBeVisible();
  await page.goto('/unknown');
  await expect(page.getByText('Page not found.')).toBeVisible();
  await page.getByRole('link', { name: 'Go to your garden' }).click();
  await expect(page.getByRole('heading', { name: 'Your garden' })).toBeVisible();
});
